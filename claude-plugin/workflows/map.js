// args: { scope: 'idea' | 'app' | 'screens', requirements?: string, project?: string, task?: string, push?: boolean,
//         screens?: false (scope app: never switch to the manifest — the terrain is wanted), areas?: string[] (screens: only these),
//         commit?: boolean (screens: commit the manifest and app map, default true),
//         repo?: absolute path (screens: every agent works there, cd first; the run stops when Detect reports another repo) }
const scope = (args && args.scope) || 'app'
const requirements = (args && args.requirements) || ''
const project = (args && args.project) || ''
const task = (args && args.task) || ''
const push = !(args && args.push === false)
const repo = (args && args.repo) || ''

if (scope === 'screens' || (scope === 'app' && !(args && args.screens === false))) {
  phase('Detect')
  const detected = await agent(withRepo(withPreamble(UILOOP_DETECT_PROMPT), repo), { label: 'detect', phase: 'Detect', effort: 'low', schema: UILOOP_DETECT_SCHEMA })
  const wrongRepo = repoProblem(repo, detected && detected.repo)
  if (wrongRepo) throw new Error(`map: ${wrongRepo} — nothing was changed; relaunch with repo set to the checkout to map`)
  if (detected && detected.configured) return await mapScreens(detected.config)
  if (scope === 'screens') throw new Error(`map: scope screens needs a uiLoop section in vybava.config.ts (${(detected && detected.reason) || 'detect failed'}) — \`vybava ui-loop init\` scaffolds it`)
  log(`map: no ui-loop here (${(detected && detected.reason) || 'detect failed'}); mapping the terrain`)
}

// The ui-loop screen manifest (Výbava docs/uiloop.md "The manifest
// contract"): explorers EXTEND <dir>/screens/<area>.ts, one area group each,
// so no two write one file; one validator checks and renders the app map.
// ≤ 8 explorers (two phases of 4) + Detect + Validate = 10 agents a run.
async function mapScreens(cfg) {
  const want = args && args.areas ? [].concat(args.areas) : []
  const areas = (cfg.areas || []).filter(a => !want.length || want.includes(a))
  if (!areas.length) throw new Error(`map: no uiLoop area to map${want.length ? ` among ${want.join(', ')}` : ''}`)
  const per = Math.ceil(areas.length / 8)
  const groups = []
  for (let i = 0; i < areas.length; i += per) groups.push(areas.slice(i, i + per))
  const explorer = g => () => agent(withRepo(withPreamble(withUiLoop(
    `Extend the ui-loop screen manifest for area${g.length > 1 ? 's' : ''} ${g.join(', ')} (apps: ${cfg.apps.join(', ')}).\n` +
    `The API is \`${cfg.dir}/vendor/manifest.ts\` + \`${cfg.dir}/vendor/project.ts\` (defineScreens, Screen, Step, Recipe) and \`${cfg.dir}/vendor/states.ts\`; the repo's hooks are \`${cfg.dir}/project.ts\`. Your files: ${JSON.stringify(g.map(a => `${cfg.dir}/screens/${a}.ts`))} — a missing one is created in the style of its siblings; never write any other area's file.\n` +
    `Inventory the area from the app's own route tables, navigators and components: every route × tab × overlay (dialog, drawer, menu, popover, phone sheet, stacked layer) × state — empty / error / loading through the \`states.ts\` request mocks (\`listStates\` for a list), unsaved changes, a validation error, denied and read-only personas (\`as\`). Add a Screen for each one the manifest lacks, with the recipe that reaches it (\`before\` mocks, \`open\` steps ending in a wait, \`ready\`), \`sourceFiles\` that exist, \`parentId\`/\`variantOf\` for overlays and states, \`app\` when there are several apps. One that cannot be reached with the seed data gets \`unreachable: '<why>'\`; one whose recipe writes gets \`destructive: true\`.\n` +
    `EXTEND ONLY: never delete, rename, reorder or rewrite an existing entry — one you believe wrong is a problems line naming its id. Run \`vybava ui-loop check --json\` and fix what it reports in the entries you added. Never run a capture, never commit.\n` +
    `Return your areas, files, the screen count before, how many you added and the unreachable ones with why.`
  )), repo), { label: `screens:${g.join('+')}`, phase: 'Explore', schema: UILOOP_MANIFEST_SCHEMA })
  phase('Explore')
  const reports = []
  for (let i = 0; i < groups.length; i += 4) reports.push(...(await parallel(groups.slice(i, i + 4).map(explorer))).filter(Boolean))
  const covered = new Set(reports.flatMap(r => r.areas))
  const missed = areas.filter(a => !covered.has(a))
  log(`map: ${reports.reduce((n, r) => n + r.added, 0)} screens added across ${covered.size}/${areas.length} areas${missed.length ? `; explorers failed for ${missed.join(', ')}` : ''}`)

  phase('Validate')
  const commit = !(args && args.commit === false)
  const result = await agent(withRepo(withPreamble(withUiLoop(
    `Validate the ui-loop screen manifest the explorers just extended (${JSON.stringify(reports.map(r => ({ areas: r.areas, files: r.files, added: r.added, problems: r.problems || [] })))}).\n` +
    `1. \`vybava ui-loop check --json\`: fix every MANIFEST_INVALID problem in the newly added entries (the diff against HEAD shows which); an existing entry's problem is reported, not rewritten.\n` +
    `2. \`vybava ui-loop map\` renders \`${cfg.appMap || 'uiLoop.appMap'}\`; \`vybava ui-loop check --json\` again must report the app map fresh.\n` +
    (commit ? `3. Commit ${cfg.dir}/screens/ and the app map path-limited ("ui-loop: map screens (${areas.join(', ')})").\n` : '3. Do not commit.\n') +
    `Return ok, the screen and capture counts, screens per area, the app map path${commit ? ', the commit' : ''} and every problem left.`
  )), repo), { label: 'validate', phase: 'Validate', schema: UILOOP_MAP_SCHEMA })
  if (!result) throw new Error('map: validating the screen manifest failed — run `vybava ui-loop check --json`')
  const problems = [...reports.flatMap(r => r.problems || []), ...(result.problems || []), ...missed.map(a => `area ${a}: its explorer failed — rerun map with areas: ["${a}"]`)]
  return { scope: 'screens', ok: result.ok, screens: result.screens, captures: result.captures || 0, perArea: result.perArea || [], appMap: result.appMap, commit: result.commit || '', added: reports.reduce((n, r) => n + r.added, 0), unreachable: reports.flatMap(r => r.unreachable || []), problems }
}

const LAYERS = [
  { key: 'routes', ask: 'every route/screen a user can reach: path, title, implementing file, auth needed, how to reach it with data on screen; plus the 3-8 end-to-end journeys a real user walks (title, steps, roles).' },
  { key: 'model', ask: 'the data model and the doors around it: entities, their store/tables, the API/MCP/CLI doors that read and write them, and the ONE door each write is supposed to go through.' },
  { key: 'components', ask: 'the component and design-system layer: shared components, layout shells, tokens/scales, the pattern a new screen is expected to copy, and the places two implementations of one thing already exist.' },
  { key: 'tests', ask: 'the test estate: frameworks in use, where e2e/unit tests live, fixtures and seeds a test can rely on, and what has no coverage.' },
]

const LAYER_SCHEMA = {
  type: 'object',
  properties: {
    layer: { type: 'string' },
    projectType: { type: 'string', enum: ['web', 'expo', 'cli', 'other'] },
    routes: TERRAIN_SCHEMA.properties.routes,
    journeys: TERRAIN_SCHEMA.properties.journeys,
    facts: { type: 'array', items: { type: 'object', properties: { what: { type: 'string' }, file: { type: 'string' }, note: { type: 'string' } }, required: ['what', 'file'] } },
    extendPoints: TERRAIN_SCHEMA.properties.extendPoints,
    duplicationRisks: TERRAIN_SCHEMA.properties.duplicationRisks,
    openQuestions: TERRAIN_SCHEMA.properties.openQuestions,
  },
  required: ['layer', 'facts'],
}

phase('Explore')
const focus = scope === 'idea'
  ? `The idea under consideration:\n${requirements}\nRead for what this idea would touch, reuse or duplicate — the parts of the system it should EXTEND rather than rebuild.`
  : 'Read for a full review pass of the whole app: completeness matters more than depth — every reachable route counts.'

const layers = (await parallel(LAYERS.map(l => () => agent(withPreamble(
  `Read-only exploration of this repository, layer: ${l.key}.\n${focus}\n\nReport ${l.ask}\nEvery fact names a real repo-relative file. Prefer the repo's own route tables, navigators, generators and docs over guessing from file names. Say what you could not determine as an open question.`
), { label: `explore:${l.key}`, phase: 'Explore', agentType: 'Explore', schema: LAYER_SCHEMA })))).filter(Boolean)

if (!layers.length) throw new Error('map: every explorer failed — nothing to synthesize')
log(`map: ${layers.length}/${LAYERS.length} layers read`)

phase('Synthesize')
const terrain = await agent(withPreamble(
  `Synthesize ONE terrain for scope "${scope}"${project ? ` of project ${project}` : ''} from these layer reports:\n${JSON.stringify(layers)}\n\n` +
  (scope === 'idea' ? `Idea requirements:\n${requirements}\n\n` : '') +
  `Produce: the route inventory (deduplicated, every entry with a file), the journeys, the extend points (where the idea/pass should build on what exists), the duplication risks (an existing thing the idea would re-implement), and the open questions a brainstorm must settle.\n` +
  (push
    ? `Then push it as a vitrinka artifact page titled "Terrain — ${scope === 'idea' ? (requirements.slice(0, 60) || 'idea') : 'app'}" following the vitrinka artifact skill (Skill tool: vitrinka:artifact)${task ? `, attached to task ${task}` : ''}${project ? `, project ${project}` : ''}; the page holds the same content as readable sections with file references. Return the server-returned artifact url as terrainUrl and its board as boardUrl.`
    : 'Do not push anything; return the terrain only.')
), { label: 'terrain', phase: 'Synthesize', schema: TERRAIN_SCHEMA })

if (!terrain) throw new Error('map: synthesis failed')
log(`map: ${terrain.routes.length} routes, ${(terrain.journeys || []).length} journeys, ${(terrain.duplicationRisks || []).length} duplication risks${terrain.terrainUrl ? ' → ' + terrain.terrainUrl : ''}`)
return terrain
