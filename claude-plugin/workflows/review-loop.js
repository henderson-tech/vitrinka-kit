    // batch's unread screens are no defect: no review is routed to them again.
    // A never-shot screen a reviewer listed anyway is neither: state.screens
    // never held it: the rig lane repairs it, or gapsLine names it at the gate.
    const stalledScreens = new Set(blocked.flatMap(b => screensOf(b.batch)))
    const ids = [...new Set(out.review.unreviewed.map(u => String(u).split(/[\s(@]/)[0]).filter(id => id && !notShot.includes(id)))].sort()
    const defects = ids.filter(id => !stalledScreens.has(id))
    const unread = ids.filter(id => stalledScreens.has(id))
