// ---- lib/uiloop-review.js — review-loop's ui-loop mode: one stage of a pass per run
// Drives `vybava ui-loop` (Výbava docs/uiloop.md). A pass is
// capture → review → fix → verify (the next pass's capture), and each run
// does ONE stage so it stays within ≤ 4 agents a phase and ≤ 10 a run.
// Every stage starts with a low-effort Prepare agent that relays
// `vybava ui-loop state --json` (and, for review, `batches`; for fix,
// `lanes`) verbatim, so `stage: 'auto'` (the default) resumes wherever the
// files say — after a cutoff too. No agent ever enumerates screens, raw
// files or backlog items: the verbs own every list and agents read bodies
// from disk by key. The run returns `next`: the args of the run to chain.
//
//   <out>/pass-<n>/shots/…                  vybava ui-loop run (+ rsync from the devbox)
//   <out>/pass-<n>/publish/{plan,index}.json vybava ui-loop split / publish
//   <out>/pass-<n>/publish/boards.json      the Boards agent: each area's set board (one per area, every pass), laid out
//   <out>/pass-<n>/review/batches.json      vybava ui-loop batches: the one batch definition
//   <out>/pass-<n>/review/raw/<batch>.json  one reviewer batch, written by its reviewer
//   <out>/pass-<n>/review/backlog.draft.json vybava ui-loop merge-review
//   <out>/pass-<n>/review/backlog.json      the Synthesize agent (scoreboard contract, v1)
//   <out>/pass-<n>/scoreboard.{json,md}     vybava ui-loop scoreboard
//   <out>/pass-<n>/fix/lanes.json           vybava ui-loop lanes: the fix lanes by ownership
//   <out>/pass-<n>/fix/<key>.json           one fix item's checkpoint (never committed)
const UILOOP_WRAP = 'devbox run --max-wait 45m -- {cmd}'
const UILOOP_MAX_REVIEWERS = 4 // + Prepare, Synthesize, Scoreboard and Gate fit the shared budget
const UILOOP_MAX_LANES = 4 // a phase; + Prepare and Settle = 10 a run

async function uiLoopReview(A, run = workflowRun(A)) {
  const cap = Math.max(1, Math.min(12, A.cap || 6))
  const list = v => (Array.isArray(v) ? v : v ? String(v).split(',') : []).map(s => String(s).trim()).filter(Boolean)
  const wrap = A.wrap || UILOOP_WRAP
  // Every prompt: the repo pin (when `repo` is given), then the preamble.
  const brief = p => withRepo(withPreamble(p), A.repo)
  const badRepo = repoProblem(A.repo, A.repo)
  if (badRepo) throw new Error(`review-loop (ui-loop): ${badRepo}`)

  // The stage-specific lists ride the Prepare agent: only when that stage runs.
  const asked = A.stage && A.stage !== 'auto' ? A.stage : ''
  const when = s => (asked ? (asked === s ? 'Now' : '') : `When state's data.next.stage is "${s}"`)
  const passFlag = A.pass ? ` --pass ${A.pass}` : ''
  const batchStep = when('review')
  const laneStep = when('fix')
  phase('Prepare')
  const prep = await run.agent(brief(withUiLoop(
    `Relay the ui-loop state of this checkout. Run the commands below and return their envelopes' \`data\` VERBATIM — every array element, however long; never summarize, sample or recount anything yourself. Change nothing beyond what the commands write.\n` +
    `1. The repo you are in (\`git rev-parse --show-toplevel\`, absolute), the branch, and the devbox workspace from \`devbox url --json\` (empty when none).\n` +
    `2. \`vybava ui-loop check --json --no-ts\`: a CONFIG_MISSING diagnostic (or no vybava.config.ts, or no \`vybava\` binary) means configured=false and you stop; every other diagnostic is a problems line.\n` +
    `3. \`vybava ui-loop state --json --cap ${cap}${passFlag}\` → its \`data\` as state (its diagnostics go to problems). It needs vybava v0.25.0 or later: an unknown command means \`brew upgrade --cask vybava\` first.\n` +
    (batchStep ? `4. ${batchStep}: \`vybava ui-loop batches --json --pass <state.pass>${A.batch ? ` --size ${A.batch}` : ''}\` → its \`data\` as batches.\n` : '') +
    (laneStep ? `${batchStep ? 5 : 4}. ${laneStep}: \`vybava ui-loop lanes --json --pass <state.pass> --max ${UILOOP_MAX_LANES}${list(A.primitives).length ? ` --primitives ${list(A.primitives).join(',')}` : ''}\` → its \`data\` as lanes.\n` : '')
  )), { label: 'prepare', phase: 'Prepare', effort: 'low', schema: UILOOP_PREP_SCHEMA })
  if (!prep) throw new Error('review-loop (ui-loop): prepare failed')
  const wrongRepo = repoProblem(A.repo, prep.repo)
  if (wrongRepo) throw new Error(`review-loop (ui-loop): ${wrongRepo} — nothing was changed; relaunch with repo set to the checkout the pass belongs to`)
  if (!prep.configured) throw new Error('review-loop (ui-loop): this repo has no uiLoop section in vybava.config.ts — run `vybava ui-loop init`, then `vitrinka:map` with scope "screens"')
  const state = prep.state
  if (!state || !state.next) throw new Error('review-loop (ui-loop): prepare relayed no `vybava ui-loop state` envelope — re-run the stage (vybava v0.25.0+)')
  // The screen count is the review's whole scope: an empty scope with shots on
  // disk once read as "every area reviewed" and synthesized a backlog from 7
  // of 31 batches (pwf-ui pass 1). Never proceed on it.
  if ((state.shots || 0) > 0 && !state.screens) throw new Error(`review-loop (ui-loop): prepare returned no screens for pass ${state.pass} although it counted ${state.shots} shots — relay \`vybava ui-loop state\` verbatim; re-run the stage`)
  const cfg = state.config || { areas: [], apps: [] }
  if (A.expectedHead && state.headSha !== A.expectedHead) throw new Error('review-loop (ui-loop): input revision changed; start a fresh pass')
  const recovery = state.recovery || A.recovery
  const staleCapture = !!state.pass && (!state.capturedHeadSha || state.sourceUnchanged !== true)
  const resumeFix = state.next.stage === 'fix' && !!state.capturedHeadSha && state.hasBacklog
  const auto = staleCapture && !resumeFix && !recovery ? { stage: 'capture', resume: false, reason: 'application source differs from captured revision; capture again' } : state.next
  let stage = staleCapture ? auto.stage : asked || auto.stage
  // A verify cut off before its publish left a new, unpublished pass: finish
  // that pass (capture resumes it) instead of shooting yet another one.
  if (stage === 'verify' && auto.stage === 'capture' && auto.resume) stage = 'capture'
  log(`review-loop (ui-loop): pass ${state.pass} on ${prep.branch} — auto says ${auto.stage} (${auto.reason}); running ${stage}`)
  const carry = Object.assign({}, A, { mode: 'ui-loop', stage: undefined, only: undefined, pass: undefined, agentBudget: undefined, expectedHead: undefined, recovery: undefined })
  const why = stage === auto.stage ? auto.reason : `stage ${stage} requested (auto would run ${auto.stage}: ${auto.reason})`
  const out = { mode: 'ui-loop', stage, pass: state.pass, reason: why, boards: state.boards || [], problems: prep.problems || [] }
  const nextOf = s => (s ? { stage: s, args: Object.assign({}, carry, { stage: s }) } : null)
  const passDir = state.passDir || `${cfg.out}/pass-${state.pass}`

  if (recovery) {
    phase('Recover')
    const settleRecovery = recovery.kind === 'settle'
    const settleObligations = settleRecovery ? `Replay Settle's obligations even when every item is already checkpointed and the application tree is clean: read ALL ${passDir}/fix/*.json checkpoints, apply every deferred i18n string to every locale catalog, retain their API notes beside primitive source, and finish the recovery keys' i18n-only or foreign blocked checkpoints from the backlog. Derive catalog ownership from the app's configuration; extend the durable marker's dirs before editing any catalog. Run the repo's type-check on Devbox and confirm its shared dev server is green. Fix and commit only this round's errors; report pre-existing errors. Return obligationsReplayed=true, green, ran and failures only after those steps succeed. A clean tree alone cannot clear Settle recovery. ` : ''
    const recovered = await run.agent(brief(withUiLoop(
      `Recover ONLY the interrupted writer ${recovery.lane} of pass ${state.pass}, BEFORE checkpoint filtering or recapture. Ownership: ${JSON.stringify(recovery)}. Read ${passDir}/fix/recovery.json (when absent, recreate it atomically from this bounded identity before any edit), git status and the named items/checkpoints. Finish or remove only your in-flight edits within those dirs and their item files; commit source path-limited after the repo's gates. Never revert another writer or unknown edits. Recheck each named checkpoint's commit, source digests, API notes and reason; refresh a checkpoint only after its source commit. Keep the spec and manifests unchanged. Confirm the application tree has no uncommitted source outside pass output/.vitrinka before removing ONLY ${passDir}/fix/recovery.json. If ownership is unclear or gates fail, keep the marker and report the blocker. Return treeCleanOfMine and recoveryCleared=true only after that verified cleanup and marker removal. ${settleObligations}`
    , true)), { label: `recover:${recovery.lane}`, phase: 'Recover', schema: { type: 'object', properties: { obligationsReplayed: { type: 'boolean' }, green: { type: 'boolean' }, ran: { type: 'array', items: { type: 'string' } }, failures: { type: 'array', items: { type: 'string' } }, treeCleanOfMine: { type: 'boolean' }, recoveryCleared: { type: 'boolean' }, problems: { type: 'array', items: { type: 'string' } } }, required: ['treeCleanOfMine', 'recoveryCleared', ...(settleRecovery ? ['obligationsReplayed', 'green', 'ran', 'failures'] : [])] } })
    const settlePassed = !settleRecovery || (recovered && recovered.obligationsReplayed === true && recovered.green === true && (recovered.ran || []).length > 0 && !(recovered.failures || []).length)
    const clear = settlePassed && recovered && recovered.treeCleanOfMine === true && recovered.recoveryCleared === true && !(recovered.problems || []).length
    return Object.assign(out, { stage: 'fix', next: { stage: clear ? 'auto' : 'fix', args: Object.assign({}, carry, { pass: state.pass, stage: clear ? 'auto' : 'fix', recovery: clear ? undefined : recovery }) }, receipt: completionReceipt({ problems: [...out.problems, ...((recovered && recovered.problems) || []), ...((recovered && recovered.failures) || []), clear ? 'writer recovered; read stage evidence again' : 'interrupted writer still needs recovery'] }) })
  }
  const uiGateSchema = { ...GATE_SCHEMA, properties: { ...GATE_SCHEMA.properties, sourceUnchanged: { type: 'boolean' } }, required: [...GATE_SCHEMA.required, 'sourceUnchanged'] }
  const verifiedGate = gate => gatePassed(gate) && gate.sourceUnchanged === true && !!state.capturedHeadSha && state.sourceUnchanged === true
  const verifyGate = () => run.agent(brief(
    `Verify this UI pass without editing or committing. Run the repo's type/build/test gates where CLAUDE.md prescribes; report testsExecuted from runner counts; zero tests cannot pass an expected suite. Check the application tree and the tested Devbox source against capturedHeadSha ${state.capturedHeadSha}, excluding only ${cfg.out} and .vitrinka/. Include staged, unstaged and untracked files. No source edits are allowed. Return sourceUnchanged, green, ran, failures and headSha AFTER verification.`
  ), { label: 'gate:ui-loop', phase: 'Verify', schema: uiGateSchema })
  if (staleCapture && !resumeFix && !recovery && state.pass >= cap) return Object.assign(out, { next: null, receipt: completionReceipt({ problems: [...out.problems, `cap of ${cap} passes reached with stale captured source`] }) })
  const retryGate = gate => {
    const attempts = (A.gateRetries || 0) + 1
    const failures = [...((gate && gate.failures) || [])]
    if (!gate) failures.push('verification agent failed')
    else if (gate.sourceUnchanged !== true) failures.push('application source changed during verification')
    else if (!(gate.testsExecuted > 0) || !(gate.ran || []).length) failures.push('verification has no executed test evidence')
    else if (!gate.green || !gate.headSha) failures.push('verification gate did not pass')
    const stage = gate && gate.sourceUnchanged === false ? 'capture' : 'auto'
    return Object.assign(out, { next: attempts < 3 ? { stage, args: Object.assign({}, carry, { stage, gateRetries: attempts }) } : null, receipt: completionReceipt({ problems: [...out.problems, ...failures] }) })
  }
  if (stage === 'done') {
    if (!state.hasBacklog || (state.review.left || []).length || !state.scoreboardCurrent || state.backlog.reviewed !== state.screens) {
      return Object.assign(out, { next: nextOf('review'), receipt: completionReceipt({ problems: [...out.problems, 'review coverage or the durable scoreboard receipt is missing or stale'] }) })
    }
    const gate = await verifyGate()
    if (!verifiedGate(gate)) return retryGate(gate)
    return Object.assign(out, { next: null, receipt: completionReceipt({ complete: !state.backlog.open && !!state.shots && state.published && verifiedGate(gate), problems: out.problems, open: state.backlog.open ? [{ title: `${state.backlog.open} open UI findings` }] : [], evidence: verifiedGate(gate) ? [{ pass: state.pass, shots: state.shots, headSha: gate.headSha, ran: gate.ran }] : [] }) })
  }
  if ((stage === 'review' || stage === 'fix') && !(state.pass && state.published)) throw new Error(`review-loop (ui-loop): stage ${stage} needs a published pass — ${auto.reason}; run stage capture`)
  if (stage === 'fix' && !state.hasBacklog) throw new Error(`review-loop (ui-loop): pass ${state.pass} has no review/backlog.json — run stage review`)
  if (stage === 'verify' && !state.hasBacklog) throw new Error(`review-loop (ui-loop): verify needs a reviewed pass — ${auto.reason}`)

  // ---- capture | verify: one `ui-loop run` on the devbox, rsync back, split, publish, board sections
  if (stage === 'capture' || stage === 'verify') {
    const resume = stage === 'capture' && auto.stage === 'capture' && auto.resume && !A.fresh
    if (!resume && state.pass >= cap) return Object.assign(out, { next: null, receipt: completionReceipt({ problems: [...out.problems, `cap of ${cap} passes reached; another capture is required`] }) })
    // The verify selection lives on disk (open items' screens + what done
    // checkpoints touched); only its emptiness is known here, from the counts.
    const verifyOnly = stage === 'verify'
    const fixed = ((state.checkpoints || {}).byStatus || {}).done || 0
    if (verifyOnly && !fixed && !(state.backlog || {}).open) return Object.assign(out, { next: null, reason: 'nothing touched and nothing open — no verify pass needed' })
    const only = verifyOnly ? ['"$ONLY"'] : staleCapture ? [] : list(A.only)
    const flags = [
      list(A.apps).length ? `--app ${list(A.apps).join(',')}` : '',
      only.length ? `--only ${only.join(',')}` : '',
      list(A.viewports).length ? `--viewports ${list(A.viewports).join(',')}` : '',
      list(A.themes).length ? `--themes ${list(A.themes).join(',')}` : '',
      A.workers ? `--workers ${A.workers}` : '',
      resume ? `--resume --pass ${state.pass}` : '',
    ].filter(Boolean).join(' ')
    const label = stage === 'verify' ? 'verify' : 'capture'
    phase('Capture')
    const cap1 = await run.agent(brief(withUiLoop(
      `${verifyOnly ? `Verify pass: re-shoot, as a NEW pass, the screens pass ${state.pass}'s fix round touched plus every screen an open backlog item names. Compute that list on disk, never by hand: \`ONLY=$(${verifyOnlyCommand(passDir)})\`.` : resume ? `Finish pass ${state.pass}: it holds shots that are not published.` : 'Capture a new ui-loop pass.'}\n` +
      (resume && state.shots ? `Shots already exist: when report.json shows every selected shot ok or unreachable, skip straight to step 3.\n` : '') +
      `1. \`vybava ui-loop check --json\` must pass (a VENDOR_DRIFT is fixed with \`vybava ui-loop sync\` and committed path-limited; any other diagnostic is a problems line and you stop).\n` +
      `Before starting the runner, confirm the application tree is clean against HEAD (including staged and untracked source) and record that HEAD. The updated CLI persists capture.json before running the capture. On resume retain and validate the original capture.json revision; never invent provenance for a legacy pass.\n` +
      `2. \`vybava ui-loop run ${flags} --wrap "${wrap}" --json\` from the repo root. The capture runs in the devbox workspace${prep.workspace ? ` (${prep.workspace})` : ''}, next to the app, never on the Mac. A run cut short is finished with the same command plus \`--resume\`, never by restarting the container.\n` +
      `3. Bring the pass back — devbox sync is one-way: \`rsync -a devops:ws/<workspace>/<app>/<out>/pass-<n>/ <out>/pass-<n>/\` with <workspace> from \`devbox url --json\` (docs/uiloop.md "On a Devbox").\n` +
      `4. \`vybava ui-loop split --json\`, then \`vybava ui-loop publish --json\`; a set that still fails after its retries is re-published alone with \`--sets <key>\` once, then reported.\n` +
      `After capture and rsync, read capture.json and validate the original revision against both checkout and tested Devbox source, excluding only uiLoop.out and .vitrinka/. Report capturedHeadSha and sourceUnchanged; stop on application drift. Never overwrite the original marker. Return the pass, its passDir, the shot count by status (report.json), published, and every set {key, area, url, status}.`
    )), { label, phase: 'Capture', schema: UILOOP_CAPTURE_SCHEMA })
    if (!cap1) throw new Error(`review-loop (ui-loop): ${label} failed — run stage auto: when the pass was created it resumes that pass, otherwise it runs ${stage} again`)
    out.pass = cap1.pass
    out.capture = { shots: cap1.shots, byStatus: cap1.byStatus || {}, published: cap1.published }
    out.problems.push(...(cap1.problems || []))
    if (!cap1.capturedHeadSha || cap1.sourceUnchanged !== true) return Object.assign(out, { next: nextOf('capture'), receipt: completionReceipt({ problems: [...out.problems, 'captured application source changed or lacks provenance'] }) })
    if (!cap1.published) return Object.assign(out, { next: nextOf('capture') })

    phase('Boards')
    const newDir = cap1.passDir || `<out>/pass-${cap1.pass}`
    const prefix = cfg.boardPrefix || 'ui-loop'
    const title = `Pass ${cap1.pass}${stage === 'verify' ? ' — verify' : ''}`
    // A set key IS a board: `ui-loop publish` keeps one set per area across
    // every pass, so the set boards are the area boards — never a second one.
    const boards = await run.agent(brief(withUiLoop(
      `Lay out pass ${cap1.pass} of the ui-loop on its area set boards${cfg.project ? ` in project ${cfg.project}` : ''}, area order ${JSON.stringify(cfg.areas)}. A vitrinka set key IS a board: \`vybava ui-loop publish\` keeps ONE set per area across every pass (key \`${prefix}-<area>\`, board slug \`<project>-<branch>-${prefix}-<area>\`) and each pass adds its shots to it. Compose onto those set boards: never create a board and never delete one — the index's \`legacy\` keys are old chunk boards and stay as they are.\n` +
      `Read ${newDir}/publish/index.json: per area set its key, title, url, status and \`sections\` [{title: "Pass N · <viewport> · <theme>", viewport, theme, labels}], plus the area's \`notes\` (shots not captured: id, viewport, theme, status, step, error). Published sets: ${JSON.stringify((cap1.sets || []).filter(s => s.url))}.\n` +
      `On each area's set board (open it by the index url) upsert this pass's sections and lay out its existing shots as the listed sections, in order: one board section per entry, holding the cards whose labels it lists. At the head of the pass's first section put a "${title}" summary callout naming the shot count and how many are not ok. Render the area's notes as ONE text card "Not captured this pass" (id · viewport · theme · status · error, one line each), never as images. Earlier passes' sections stay untouched. Replay replaces this pass's summary and notes instead of duplicating them. Read \`docs {topic: "kind:board"}\` first; express placement by intent and read each board back.\n` +
      `Write [{area, url, slug, section}] to ${newDir}/publish/boards.json and return it: url and slug are the set board's, server-returned; section is the title of this pass's first section (the one the summary callout heads).`
    )), { label: 'boards', phase: 'Boards', agentType: 'vitrinka:vitrinka-publisher', schema: UILOOP_BOARDS_SCHEMA })
    if (boards) { out.boards = boards.boards; out.problems.push(...(boards.problems || [])) } else out.problems.push('boards: laying the pass out on the area set boards failed — the sets are published; rerun stage capture to lay them out')
    return Object.assign(out, { next: nextOf('review') })
  }

  // ---- review: batch reviewers per area judge each screen against the spec and the previous backlog
  if (stage === 'review') {
    const batches = prep.batches
    const bad = batchesProblem(state, batches)
    if (bad) throw new Error(`review-loop (ui-loop): ${bad}`)
    const all = batches.batches
    const doneIds = new Set(batches.done || [])
    const todo = all.filter(b => !doneIds.has(b.id)).filter(b => !list(A.areas).length || list(A.areas).includes(b.area))
    const now = todo.slice(0, Math.min(UILOOP_MAX_REVIEWERS, A.reviewers || UILOOP_MAX_REVIEWERS))
    const prev = state.previous && state.previous.open ? state.previous : null
    log(`review: ${all.length} batches, ${doneIds.size} already reviewed, ${now.length} this run, ${todo.length - now.length} left for the next run`)
    const reviewer = b => () => run.agent(brief(withUiLoop(
      `Review batch ${b.id} of ui-loop pass ${state.pass} (area ${b.area}): screens ${JSON.stringify(b.screens)} (the batch as ${passDir}/review/batches.json defines it).\n` +
      `Judge against the written spec \`${cfg.spec || 'the spec file uiLoop.spec names'}\` — read it first, owner decisions in it are final — and its hard rules: the 4pt grid, no text overflow, no horizontal scroll, safe areas respected, touch targets ≥ 44 on phone, one painter per background, dialogs sized for their content, UX that makes sense to the app's real user.\n` +
      `Files: ${passDir}/shots/<id>/<viewport>.<theme>.png (+ .full.png when the page scrolls) and its .json record (status, lint defects, consoleErrors, sourceFiles); the manifest entry is in \`${cfg.dir}/screens/${b.area}.ts\`.\n` +
      `Method: read EVERY png of every screen. ` +
      (prev ? `Pass ${prev.pass}'s open items on your screens are read from disk: \`jq -c --argjson s '${JSON.stringify(b.screens)}' '.findings[] | select(.status != "met" and (.screen as $x | $s | index($x))) | {key, screen, title, acceptance}' ${prev.file}\`. Judge each one's acceptance line: met / partly / not-met (pass ${prev.pass}'s png of the same viewport is the before). Never file one of them again as a new finding — its verdict is its entry.\n` : '') +
      `Then list what is still or newly wrong: severity broken | needs-work | polish, a title, detail (with the region in image px), the files a fix edits (repo-relative, verified to exist), an acceptance line a later reviewer can judge from a screenshot, the viewports/themes/shots (\`<id>@<viewport>.<theme>\`) it shows on, systemic=true when a shared primitive or token is the cause. Ignore invisible lint noise; mocked data and seed names are fine. A screen whose shot is missing or blank goes to unreviewed as "<screen id> (why)".\n` +
      `Write the whole batch to ${passDir}/review/raw/${b.id}.json in this shape (it is the batch's checkpoint; \`vybava ui-loop merge-review\` reads it): ${UILOOP_RAW_SHAPE}\n` +
      `Write basis ${state.reviewBasis} and screensRead (only screens whose every PNG you actually read) in the raw file too. Return only the receipt: the file, the finding and verdict counts, and the unreviewed entries.`
    )), { label: `review:${b.id}`, phase: 'Review', schema: UILOOP_REVIEW_SCHEMA })
    const fresh = []
    for (let i = 0; i < now.length; i += 4) {
      fresh.push(...(await run.parallel(now.slice(i, i + 4).map(reviewer))).filter(Boolean))
    }
    const covered = new Set([...doneIds, ...fresh.map(r => r.batch)])
    const left = all.filter(b => !covered.has(b.id))
    const inScope = left.filter(b => !list(A.areas).length || list(A.areas).includes(b.area))
    out.review = { batches: all.length, reviewedNow: fresh.length, left: left.map(b => b.id), unreviewed: [...new Set(fresh.flatMap(r => r.unreviewed || []))].sort() }
    // An `areas` limit narrows this run only: once its areas are done, the
    // chain drops it so the next run reviews the rest instead of looping.
    if (inScope.length) return Object.assign(out, { next: nextOf('review'), reason: `${inScope.length} review batches left` })
    if (left.length) return Object.assign(out, { next: { stage: 'review', args: Object.assign({}, carry, { stage: 'review', areas: undefined }) }, reason: `${left.length} review batches left outside areas ${list(A.areas).join(', ')}` })

    phase('Synthesize')
    // merge-review folds the raw batches and the previous backlog on disk and
    // names the few keys that need judgement; the agent handles only those.
    const synth = await run.agent(brief(withUiLoop(
      `Write the backlog of ui-loop pass ${state.pass} to ${passDir}/review/backlog.json, in the \`vybava ui-loop scoreboard\` contract (docs/uiloop.md "Scoreboard and the review backlog": {v: 1, pass, reviewed, findings}, unknown keys rejected).\n` +
      `1. \`vybava ui-loop merge-review --pass ${state.pass} --json\`. It merged every raw batch and pass ${prev ? prev.pass : '<previous>'}'s backlog into ${passDir}/review/backlog.draft.json — exact duplicates folded, previous items carrying their verdict as status, \`reviewed\` computed from the batches minus the unreviewed screens. A REVIEW_INCOMPLETE diagnostic means batches are incomplete: preserve the valid partial draft and name every missing/unread screen in unreviewed; never mark them clean or drop the judged screens' findings.\n` +
      `2. Handle ONLY what its envelope names; never read or rewrite the other items. \`unjudged\`: previous items no reviewer judged; they stand as not-met — look at their screens' shots and set the verdict when you can, but never met on a screen listed in \`unreviewed\`. \`problems\`: raw findings left out (\`{batch, index, missing}\` — read review/raw/<batch>.json .findings[index]); repair each from the code and the shots and add it (status open, key = its screen + title slug), or drop it with why in problems. \`invalid\`: contract breaks to fix.\n` +
      `3. Apply those edits to a copy of the draft with jq (select by key) and write it as ${passDir}/review/backlog.json. Never change \`reviewed\` and never invent a finding. The pass directory is gitignored environment output: never commit it.\n` +
      `Also write {"basis":"${state.reviewBasis}"} to ${passDir}/review/basis.json; never change the fingerprinted spec or manifests.\n` +
      `4. Validate with \`vybava ui-loop scoreboard --pass ${state.pass} --json\` (a BACKLOG_INVALID diagnostic names what to fix).\n` +
      `Return the file, the finding and open counts of the written backlog, how many flagged keys you settled, len(reviewed), and merge-review's \`unreviewed\` verbatim.`
    )), { label: 'synthesize', phase: 'Synthesize', schema: UILOOP_SYNTH_SCHEMA })
    if (!synth) throw new Error('review-loop (ui-loop): synthesis failed — run stage review again; the raw batches are kept')
    out.backlog = { file: synth.backlogFile, findings: synth.findings, open: synth.open }
    out.review.judged = synth.reviewed
    out.review.unreviewed = [...new Set([...out.review.unreviewed, ...(synth.unreviewed || [])])].sort()
    // A screen no reviewer could judge (missing or blank shot) is never
    // silently counted reviewed — it is named, with the recapture that fixes it.
    const ids = [...new Set(out.review.unreviewed.map(u => String(u).split(/[\s(@]/)[0]).filter(Boolean))].sort()
    if (ids.length) out.problems.push(`${ids.length} screens could not be reviewed (missing or blank shots): recapture with review-loop {mode: "ui-loop", stage: "capture", only: ${JSON.stringify(ids)}}`)
    out.problems.push(...(synth.problems || []))

    phase('Scoreboard')
    const score = await run.agent(brief(withUiLoop(
      `Score ui-loop pass ${state.pass}: \`vybava ui-loop scoreboard --pass ${state.pass} --json\`, then read ${passDir}/scoreboard.md.\n` +
      `On each area set board ${JSON.stringify(out.boards)} post a callout in this pass's first section (the row's \`section\`, headed by the "Pass ${state.pass}" summary callout): that area's row (screens broken / needs-work / polish / clean, findings open / met / partly / not-met, lint defects per rule, console errors, shots not ok, and the delta against the previous pass) and the totals line. Read \`docs {topic: "kind:board"}\` first; the callout replaces an earlier scoreboard callout of the same section. Read every board back. Only after all callouts are confirmed, read \`vybava ui-loop state --pass ${state.pass} --json\` for scoreboardBasis, write {basis: scoreboardBasis, posted: [{area, url}]} atomically to ${passDir}/review/scoreboard-receipt.json (temp file, fsync, rename, directory fsync), then read state back and return receiptVerified=true only when scoreboardCurrent=true. Missing or failed callouts never get a receipt. Return the scoreboard file, receiptVerified, totals and every board url you posted to.`
    )), { label: 'scoreboard', phase: 'Scoreboard', effort: 'low', schema: UILOOP_SCORE_SCHEMA })
    if (score) { out.scoreboard = { file: score.scoreboardFile, totals: score.totals || {}, posted: score.posted }; out.problems.push(...(score.problems || [])) }
    else out.problems.push('scoreboard: posting failed — rerun review')
    const scoreOk = !!score && score.receiptVerified === true && !(score.problems || []).length
    const coverageOk = !ids.length && synth.reviewed === state.screens
    const gate = !synth.open && coverageOk && scoreOk ? await verifyGate() : null
    if (!synth.open && coverageOk && scoreOk && !verifiedGate(gate)) return retryGate(gate)
    return Object.assign(out, { next: nextOf(ids.length ? 'capture' : !scoreOk ? 'review' : synth.open ? 'fix' : !coverageOk ? 'review' : null), receipt: completionReceipt({ complete: !synth.open && coverageOk && scoreOk && verifiedGate(gate), problems: out.problems, evidence: verifiedGate(gate) ? [{ backlog: synth.backlogFile, shots: state.shots, headSha: gate.headSha, ran: gate.ran }] : [] }) })
  }

  // ---- fix: lanes by ownership (`vybava ui-loop lanes`) — primitives first, then their dirs are frozen and ≤ 4 area lanes run; Settle applies the deferred i18n and type-checks
  if (stage === 'fix') {
    const lanes = prep.lanes
    const bad = lanesProblem(state, lanes)
    if (bad) throw new Error(`review-loop (ui-loop): ${bad}`)
    const prim = lanes.primitives
    const areas = lanes.areas
    const foreign = lanes.foreign || []
    const i18nItems = lanes.i18n || []
    log(`fix: ${prim.length} primitives lanes, ${areas.length} area lanes, ${lanes.frozen.length} frozen dirs, ${foreign.length} foreign, ${i18nItems.length} i18n-only, ${lanes.finished} already finished`)
    const laneBrief = (l, kind, apiNotes) => brief(withUiLoop(
      `You are fix lane ${l.lane} (${kind}) of ui-loop pass ${state.pass}, on branch ${prep.branch}. The spec is \`${cfg.spec}\` (read it first; its rules and owner decisions are final); the apps run on the devbox${prep.workspace ? ` workspace ${prep.workspace}` : ''} and stay running.\n` +
      `Before any source edit, atomically write ${passDir}/fix/recovery.json = ${JSON.stringify({ lane: l.lane, kind, dirs: l.dirs, keys: l.keys })} (temp/fsync/rename/directory sync). It is the durable writer identity. Keep it on failure or dirty source; remove it only after all your source edits are committed and the application tree is clean outside pass output/.vitrinka.\n` +
      `WHAT TO FIX: these backlog keys, in this order (worst first): ${JSON.stringify(l.keys)}.\n` +
      `Read each item's full body from ${passDir}/review/backlog.json by key (\`jq '.findings[] | select(.key=="<key>")' ${passDir}/review/backlog.json\`): title, detail, acceptance, files, screen, viewports, themes, shots. Look at its shots under ${passDir}/shots/<screen>/<viewport>.<theme>.png before and while you fix.\n` +
      `Checkpoints require basis ${state.reviewBasis}, commit, fileDigests (SHA256 of every source file this item changed) and apiChanges. Missing, reverted or stale checkpoints must be reevaluated.\nYOUR DIRS — you own the files directly inside them, not their subdirectories: ${JSON.stringify(l.dirs)}. Checkpoints go to ${passDir}/fix/<key>.json with "lane":"${l.lane}".\n` +
      (kind === 'primitives'
        ? `You own shared primitives: fix in the shared component, token or recipe so every screen using it is fixed at once. Public API changes are ADDITIVE only (nothing removed or renamed); return each in apiChanges and document it beside the changed primitive code and in each checkpoint's apiChanges. Never edit the fingerprinted spec during a fix round.\n`
        : `Primitive dirs are FROZEN (the primitives lanes finished first): never edit a file in ${JSON.stringify(lanes.frozen)}.${apiNotes.length ? ` Additions they made this round: ${JSON.stringify(apiNotes)}.` : ''} An item that needs a primitive change is checkpointed blocked with the exact change as its note.\n`) +
      `Return the done/skipped/blocked keys, remaining (keys not reached), commits, touched screens, apiChanges, i18n and treeCleanOfMine.`
    , true))
    const results = []
    const runLanes = async (ls, kind, apiNotes) => {
      const selected = ls.slice(0, Math.max(0, run.remaining() - 1)) // reserve Settle, including calls already spent on Detect/Prepare
      const batch = await run.serial(selected.map(l => () =>
        run.agent(laneBrief(l, kind, apiNotes), { label: `fix:${l.lane}`, phase: kind === 'primitives' ? 'Fix: primitives' : 'Fix: areas', schema: UILOOP_LANE_SCHEMA })), r => !!r && r.treeCleanOfMine === true)
      results.push(...batch.results.filter(Boolean))
      if (batch.failedIndex === null) return true
      out.fix = laneSummary(results)
      out.problems.push(`fix lane ${ls[batch.failedIndex].lane} failed or left dirty source; recover it before another writer`)
      out.recovery = { lane: ls[batch.failedIndex].lane, kind, dirs: ls[batch.failedIndex].dirs, keys: ls[batch.failedIndex].keys }
      return false
    }
    const recover = () => Object.assign(out, { next: { stage: 'fix', args: Object.assign({}, carry, { stage: 'fix', pass: state.pass, recovery: out.recovery }) }, receipt: completionReceipt({ problems: out.problems }) })
    let wait = ''
    if (prim.length) {
      phase('Fix: primitives')
      if (!await runLanes(prim, 'primitives', state.checkpointApiNotes || [])) return recover()
      const fin = finishedBy(results)
      const unfinished = prim.flatMap(l => l.keys).filter(k => !fin.has(k))
      if (unfinished.length) wait = `${unfinished.length} primitive items unfinished — the area lanes wait for a frozen primitive API`
    }
    const apiNotes = [...(state.checkpointApiNotes || []), ...results.flatMap(r => r.apiChanges || [])]
    if (areas.length && !wait) {
      phase('Fix: areas')
      if (!await runLanes(areas, 'areas', apiNotes)) return recover()
    }
    let settle = null
    if (results.length || foreign.length || i18nItems.length) {
      phase('Settle')
      settle = await run.agent(brief(withUiLoop(
        `Settle the fix round of ui-loop pass ${state.pass} on branch ${prep.branch}. Before any edit, atomically write ${passDir}/fix/recovery.json with lane=settle, kind=settle, keys=${JSON.stringify([...foreign, ...i18nItems])} and dirs=the catalog/source directories you will edit. Keep the marker on cutoff/failure/dirty source; remove it only after all deferred strings are applied, the type-check and shared dev server are green, source is committed and the application tree is verified clean. The lanes are done; you own the i18n catalogs this step. Never edit the fingerprinted spec.\n` +
        `1. Strings: every string the round needs is in its checkpoints — \`jq -c '.i18n[]?' ${passDir}/fix/*.json\`${results.some(r => (r.i18n || []).length) ? ` — plus these the lanes returned: ${JSON.stringify(results.flatMap(r => r.i18n || []))}` : ''}. Add each key the catalogs lack to every locale catalog the app uses (keep each file's structure, key order and formatting; an existing key keeps its value unless the fix needs a change). Commit path-limited: "fix(i18n): strings for ui-loop pass ${state.pass}".\n` +
        (i18nItems.length ? `2. These items touch only i18n catalogs; read each by key from ${passDir}/review/backlog.json, fix it in the catalogs, commit path-limited and checkpoint it (lane "settle"): ${JSON.stringify(i18nItems)}.\n` : '') +
        (foreign.length ? `3. These items name no file in this repo (their fix lands in another repo): never edit another repo — checkpoint each blocked (lane "settle") with a note naming the repo and files the fix needs: ${JSON.stringify(foreign)}.\n` : '') +
        (apiNotes.length ? `4. Retain these primitive API additions in ignored per-item checkpoints and document beside primitive source when missing, never in the fingerprinted spec: ${JSON.stringify(apiNotes)}.\n` : '') +
        `5. Type-check what the round touched the way the repo's CLAUDE.md prescribes — on the devbox, never a full build on the Mac. An error this round's commits (${JSON.stringify(results.flatMap(r => r.commits || []))}) caused you fix and commit path-limited; one that predates them you report.\n` +
        `6. Confirm the shared dev server is green (its log in the devbox workspace).\n` +
        `Checkpoints follow the lane rules: basis ${state.reviewBasis}, fileDigests (SHA256 of every source file the item changed), apiChanges and i18n, written after the commit, never committed. Never touch the database, the devbox stack or captures; never push. Return green, what you ran, failures, commits, i18nAdded and the keys you checkpointed.`
      , true)), { label: 'settle', phase: 'Settle', schema: UILOOP_SETTLE_SCHEMA })
      if (!settle) { out.recovery = { lane: 'settle', kind: 'settle', dirs: [], keys: [...foreign, ...i18nItems] }; out.problems.push('settle: the i18n / type-check step failed — run stage fix again; it re-applies every checkpoint\'s strings') }
      else out.problems.push(...(settle.problems || []), ...(settle.failures || []).map(f => `settle: ${f}`))
    }
    out.fix = Object.assign(laneSummary(results), { remaining: results.flatMap(r => r.remaining || []), apiChanges: apiNotes, settle: settle && { green: settle.green, i18nAdded: settle.i18nAdded || 0, checkpointed: settle.checkpointed || [], commits: settle.commits || [] } })
    out.handTest = 'The apps stay running on the devbox: ask the owner for a hand-test of the touched screens before the verify pass.'
    if (settle && (!settle.green || !(settle.ran || []).length || (settle.failures || []).length)) {
      out.recovery = { lane: 'settle', kind: 'settle', dirs: [], keys: [...foreign, ...i18nItems] }
      out.problems.push('settle gate did not pass')
      return recover()
    }
    if ((results.length || foreign.length || i18nItems.length) && !settle) return recover()
    if (wait) return Object.assign(out, { next: nextOf('fix'), reason: wait })
    const fin = finishedBy(results)
    for (const k of (settle && settle.checkpointed) || []) fin.add(k)
    const left = [...[...prim, ...areas].flatMap(l => l.keys), ...foreign, ...i18nItems].filter(k => !fin.has(k))
    const fixedAny = out.fix.done.length || (((state.checkpoints || {}).byStatus || {}).done || 0) > 0
    if (left.length) return Object.assign(out, { next: nextOf('fix'), reason: `${left.length} items without a checkpoint` })
    return Object.assign(out, { next: nextOf(fixedAny && state.pass < cap ? 'verify' : null), reason: fixedAny ? (state.pass < cap ? 'round checkpointed' : `cap of ${cap} passes reached`) : 'the round fixed nothing — the open items need a human' })
  }

  throw new Error(`review-loop (ui-loop): unknown stage ${stage} — capture | review | fix | verify | auto`)
}

function laneSummary(results) {
  return {
    lanes: results.map(r => r.lane),
    done: results.flatMap(r => r.done),
    skipped: results.flatMap(r => r.skipped),
    blocked: results.flatMap(r => r.blocked || []),
    commits: results.flatMap(r => r.commits || []),
    touchedScreens: [...new Set(results.flatMap(r => r.touchedScreens || []))],
    dirty: results.filter(r => !r.treeCleanOfMine).map(r => r.lane),
  }
}
