// ---- lib/uiloop-review.js — review-loop's ui-loop mode: one stage of a pass per run
// Drives `vybava ui-loop` (Výbava docs/uiloop.md). A pass is
// capture → review → fix → verify (the next pass's capture), and each run
// does ONE stage so it stays within ≤ 4 agents a phase and ≤ 10 a run.
// Every stage starts with a Prepare agent that reads the pass directory
// back, so `stage: 'auto'` (the default) resumes wherever the files say —
// after a cutoff too. The run returns `next`: the args of the run to chain.
//
//   <out>/pass-<n>/shots/…                  vybava ui-loop run (+ rsync from the devbox)
//   <out>/pass-<n>/publish/{plan,index}.json vybava ui-loop split / publish
//   <out>/pass-<n>/publish/boards.json      the Boards agent: one board per area, a section per pass
//   <out>/pass-<n>/review/raw/<batch>.json  one reviewer batch, verbatim
//   <out>/pass-<n>/review/backlog.json      the Synthesize agent (scoreboard contract, v1)
//   <out>/pass-<n>/scoreboard.{json,md}     vybava ui-loop scoreboard
//   <out>/pass-<n>/fix/<key>.json           one fix item's checkpoint
const UILOOP_WRAP = 'devbox run --max-wait 45m -- {cmd}'
const UILOOP_MAX_REVIEWERS = 4 // one bounded review phase; unfinished batches return next

async function uiLoopReview(A, run = workflowRun(A)) {
  const cap = Math.max(1, Math.min(12, A.cap || 6))
  const list = v => (Array.isArray(v) ? v : v ? String(v).split(',') : []).map(s => String(s).trim()).filter(Boolean)
  const wrap = A.wrap || UILOOP_WRAP

  phase('Prepare')
  const prep = await run.agent(withPreamble(withUiLoop(
    `Read back the ui-loop state of this checkout; change nothing.\n` +
    `1. Branch; \`vybava ui-loop check --json\` (every diagnostic goes to problems); the uiLoop section via \`vybava config show --json\` (configured=false when there is none); the devbox workspace from \`devbox url --json\` (empty when none).\n` +
    `2. The pass: ${A.pass ? `pass ${A.pass}` : 'the newest pass-<n> under <out>'} (pass 0 when <out> holds none). Count the shot records (<passDir>/shots/<id>/*.json, not the .full ones) and list each DISTINCT screen {id, area} they name once. published = publish/index.json exists and every set of publish/plan.json is pushed (a halved set counts when both halves are).\n` +
    `3. Every <passDir>/review/raw/*.json verbatim as raw; reviewedAreas = the areas whose screens are all covered by a raw file. hasBacklog and the findings of <passDir>/review/backlog.json. previousBacklog = the findings of the newest EARLIER pass with a review/backlog.json.\n` +
    `4. Every <passDir>/fix/*.json checkpoint; report valid=true ONLY when its commit is an ancestor of HEAD and the recorded fix is still present (skipped/blocked: its recorded reason still applies). Missing, reverted or unrelated commits are invalid. Read the area boards from <passDir>/publish/boards.json (or the newest earlier pass that has one).\n` +
    `5. headSha = git rev-parse HEAD. reviewBasis = SHA256 of UTF-8 JSON.stringify(entries), where each entry is [repo-relative forward-slash filename, lowercase SHA256 of its bytes], sorted by filename using JavaScript string comparison. Include ALL pass shot JSON/PNG files, the spec, and manifest .ts files (exclude vendor/); empty only without a pass. Raw reviews and backlog files carry basis; return backlogBasis from <passDir>/review/basis.json. Treat a missing or different basis as stale. Never reuse a stale review or checkpoint. Compare published digests against ui-loop publish --dry-run --json before claiming published; an old receipt alone is insufficient.`
  )), { label: 'prepare', phase: 'Prepare', schema: UILOOP_PREP_SCHEMA })
  if (!prep) throw new Error('review-loop (ui-loop): prepare failed')
  if (!prep.configured) throw new Error('review-loop (ui-loop): this repo has no uiLoop section in vybava.config.ts — run `vybava ui-loop init`, then `vitrinka:map` with scope "screens"')
  if (A.expectedHead && prep.headSha !== A.expectedHead) throw new Error('review-loop (ui-loop): input revision changed; start a fresh pass')
  if (prep.pass && !prep.reviewBasis) throw new Error('review-loop (ui-loop): pass has no content fingerprint')
  prep.raw = (prep.raw || []).filter(r => r.basis === prep.reviewBasis)
  if (prep.backlogBasis !== prep.reviewBasis) prep.hasBacklog = false
  prep.checkpoints = (prep.checkpoints || []).filter(c => c.basis === prep.reviewBasis && c.valid === true)
  prep.reviewedAreas = uniqAreas(prep.screens || []).filter(area => reviewBatches((prep.screens || []).filter(s => s.area === area), [area], A.batch || 14).every(b => prep.raw.some(r => r.batch === b.id && b.screens.every(id => (r.screensRead || []).includes(id)) && !(r.unreviewed || []).length)))
  const cfg = prep.config || { areas: [], apps: [] }
  const state = {
    pass: prep.pass, shots: prep.shots, published: prep.published, areas: uniqAreas(prep.screens || []),
    reviewedAreas: prep.reviewedAreas || [], backlog: prep.hasBacklog ? (prep.backlog || []) : null, checkpoints: prep.checkpoints || [],
  }
  const verifyGate = () => run.agent(withPreamble(
    `Verify this UI pass without editing or committing. Run the repo's type/build/test gates where CLAUDE.md prescribes; report testsExecuted from the runner counts; zero executed tests cannot pass an expected suite. Check that code has not changed since prepare at ${prep.headSha}, allowing only this pass's review/backlog and basis artifacts. A source change invalidates the captured evidence. Return green, ran, failures and headSha AFTER verification.`
  ), { label: 'gate:ui-loop', phase: 'Verify', schema: GATE_SCHEMA })
  const auto = nextStage(state, cap)
  let stage = A.stage && A.stage !== 'auto' ? A.stage : auto.stage
  // A verify cut off before its publish left a new, unpublished pass: finish
  // that pass (capture resumes it) instead of shooting yet another one.
  if (stage === 'verify' && auto.stage === 'capture' && auto.resume) stage = 'capture'
  log(`review-loop (ui-loop): pass ${prep.pass} on ${prep.branch} — auto says ${auto.stage} (${auto.reason}); running ${stage}`)
  const carry = Object.assign({}, A, { mode: 'ui-loop', stage: undefined, only: undefined, pass: undefined, agentBudget: undefined, expectedHead: undefined })
  const why = stage === auto.stage ? auto.reason : `stage ${stage} requested (auto would run ${auto.stage}: ${auto.reason})`
  const out = { mode: 'ui-loop', stage, pass: prep.pass, reason: why, boards: prep.boards || [], problems: prep.problems || [] }
  const nextOf = s => (s ? { stage: s, args: Object.assign({}, carry, { stage: s }) } : null)

  if (stage === 'verify' && !state.backlog) stage = 'capture' // changed spec/manifest: capture the current contract in full
  if (stage === 'fix' && !state.backlog && prep.published) stage = 'review' // stale review: rebuild before applying fixes
  if (stage === 'done' && (!state.backlog || state.areas.some(area => !state.reviewedAreas.includes(area)))) stage = 'review'
  out.stage = stage
  if (stage === 'done') {
    const gate = await verifyGate()
    return Object.assign(out, { next: null, receipt: completionReceipt({ complete: !state.backlog.some(isOpenItem) && !!state.shots && state.published && gatePassed(gate), problems: [...out.problems, ...(!gatePassed(gate) ? ['the UI pass has no passing verification gate'] : [])], open: state.backlog.filter(isOpenItem), evidence: gatePassed(gate) ? [{ pass: state.pass, shots: state.shots, headSha: gate.headSha, ran: gate.ran }] : [] }) })
  }
  if ((stage === 'review' || stage === 'fix') && !(prep.pass && prep.published)) throw new Error(`review-loop (ui-loop): stage ${stage} needs a published pass — ${auto.reason}; run stage capture`)
  if (stage === 'fix' && !state.backlog) throw new Error(`review-loop (ui-loop): pass ${prep.pass} has no review/backlog.json — run stage review`)
  if (stage === 'verify' && !state.backlog) throw new Error(`review-loop (ui-loop): verify needs a reviewed pass — ${auto.reason}`)

  // ---- capture | verify: one `ui-loop run` on the devbox, rsync back, split, publish, board sections
  if (stage === 'capture' || stage === 'verify') {
    const resume = stage === 'capture' && auto.stage === 'capture' && auto.resume && !A.fresh
    const only = stage === 'verify' ? verifySelection(state.backlog, state.checkpoints) : list(A.only)
    if (stage === 'verify' && !only.length) return Object.assign(out, { next: null, reason: 'nothing touched and nothing open — no verify pass needed' })
    const flags = [
      list(A.apps).length ? `--app ${list(A.apps).join(',')}` : '',
      only.length ? `--only ${only.join(',')}` : '',
      list(A.viewports).length ? `--viewports ${list(A.viewports).join(',')}` : '',
      list(A.themes).length ? `--themes ${list(A.themes).join(',')}` : '',
      A.workers ? `--workers ${A.workers}` : '',
      resume ? `--resume --pass ${prep.pass}` : '',
    ].filter(Boolean).join(' ')
    const label = stage === 'verify' ? 'verify' : 'capture'
    phase('Capture')
    const cap1 = await run.agent(withPreamble(withUiLoop(
      `${stage === 'verify' ? `Verify pass: re-shoot the ${only.length} screens pass ${prep.pass}'s fix round touched plus every screen an open backlog item names, as a NEW pass.` : resume ? `Finish pass ${prep.pass}: it holds shots that are not published.` : 'Capture a new ui-loop pass.'}\n` +
      (resume && prep.shots ? `Shots already exist: when report.json shows every selected shot ok or unreachable, skip straight to step 3.\n` : '') +
      `1. \`vybava ui-loop check --json\` must pass (a VENDOR_DRIFT is fixed with \`vybava ui-loop sync\` and committed path-limited; any other diagnostic is a problems line and you stop).\n` +
      `2. \`vybava ui-loop run ${flags} --wrap "${wrap}" --json\` from the repo root. The capture runs in the devbox workspace${prep.workspace ? ` (${prep.workspace})` : ''}, next to the app, never on the Mac. A run cut short is finished with the same command plus \`--resume\`, never by restarting the container.\n` +
      `3. Bring the pass back — devbox sync is one-way: \`rsync -a devops:ws/<workspace>/<app>/<out>/pass-<n>/ <out>/pass-<n>/\` with <workspace> from \`devbox url --json\` (docs/uiloop.md "On a Devbox").\n` +
      `4. \`vybava ui-loop split --json\`, then \`vybava ui-loop publish --json\`; a set that still fails after its retries and halving is re-published alone with \`--sets <key>\` once, then reported.\n` +
      `Return the pass, its passDir, the shot count by status (report.json), published, and every set {key, area, url, status}.`
    )), { label, phase: 'Capture', schema: UILOOP_CAPTURE_SCHEMA })
    if (cap1 && !cap1.shots) throw new Error('review-loop (ui-loop): capture executed zero shots; resume capture')
    if (!cap1) throw new Error(`review-loop (ui-loop): ${label} failed — run stage auto: when the pass was created it resumes that pass, otherwise it runs ${stage} again`)
    out.pass = cap1.pass
    out.capture = { shots: cap1.shots, byStatus: cap1.byStatus || {}, published: cap1.published }
    out.problems.push(...(cap1.problems || []))
    if (!cap1.published) return Object.assign(out, { next: nextOf('capture') })

    phase('Boards')
    const title = `Pass ${cap1.pass}${stage === 'verify' ? ' — verify' : ''}`
    const boards = await run.agent(withPreamble(withUiLoop(
      `Compose pass ${cap1.pass} of the ui-loop onto ONE board per area${cfg.project ? ` in project ${cfg.project}` : ''}: slug \`${cfg.boardPrefix || 'ui-loop'}-<area>\`, area order ${JSON.stringify(cfg.areas)}. Existing boards: ${JSON.stringify(prep.boards || [])}.\n` +
      `Published sets (each is its own source board): ${JSON.stringify((cap1.sets || []).filter(s => s.url))}.\n` +
      `On each area board add a section "${title}" — earlier pass sections stay untouched — holding that area's sets as Phone · Tablet · Desktop step clusters (by viewport, then theme) with a portal to each source set, and a summary callout at the section head naming the pass, the shot count and the shots that are not ok. Read \`docs {topic: "kind:board"}\` first; express placement by intent and read each board back. ` +
      `Write [{area, url, slug, section}] to ${cap1.passDir || `<out>/pass-${cap1.pass}`}/publish/boards.json and return it; every url is the server-returned one.`
    )), { label: 'boards', phase: 'Boards', agentType: 'vitrinka:vitrinka-publisher', schema: UILOOP_BOARDS_SCHEMA })
    if (boards) { out.boards = boards.boards; out.problems.push(...(boards.problems || [])) } else out.problems.push('boards: composing the area sections failed — the sets are published; rerun stage capture to compose them')
    return Object.assign(out, { next: nextOf('review') })
  }

  // ---- review: batch reviewers per area judge each screen against the spec and the previous backlog
  if (stage === 'review') {
    const all = reviewBatches(prep.screens || [], cfg.areas || [], A.batch)
    if (!all.length) throw new Error('review-loop (ui-loop): no screens to review; zero coverage cannot complete')
    const doneIds = new Set((prep.raw || []).map(r => r.batch))
    const todo = all.filter(b => !doneIds.has(b.id)).filter(b => !list(A.areas).length || list(A.areas).includes(b.area))
    const now = todo.slice(0, Math.min(UILOOP_MAX_REVIEWERS, A.reviewers || UILOOP_MAX_REVIEWERS, Math.max(0, run.remaining() - 3)))
    const passDir = prep.passDir || `${cfg.out}/pass-${prep.pass}`
    const prev = (prep.previousBacklog || []).filter(isOpenItem)
    log(`review: ${all.length} batches, ${doneIds.size} already reviewed, ${now.length} this run, ${todo.length - now.length} left for the next run`)
    const reviewer = b => () => run.agent(withPreamble(withUiLoop(
      `Review batch ${b.id} of ui-loop pass ${prep.pass} (area ${b.area}): screens ${JSON.stringify(b.screens)}.\n` +
      `Judge against the written spec \`${cfg.spec || 'the spec file uiLoop.spec names'}\` — read it first, owner decisions in it are final — and its hard rules: the 4pt grid, no text overflow, no horizontal scroll, safe areas respected, touch targets ≥ 44 on phone, one painter per background, dialogs sized for their content, UX that makes sense to the app's real user.\n` +
      `Files: ${passDir}/shots/<id>/<viewport>.<theme>.png (+ .full.png when the page scrolls) and its .json record (status, lint defects, consoleErrors, sourceFiles); the manifest entry is in \`${cfg.dir}/screens/${b.area}.ts\`.\n` +
      `Method: read EVERY png of every screen. ` +
      (prev.some(f => b.screens.includes(f.screen)) ? `For each previous-pass item below whose screen is in this batch, judge its acceptance line: met / partly / not-met (the previous pass's png of the same viewport is the before):\n${JSON.stringify(prev.filter(f => b.screens.includes(f.screen)).map(f => ({ key: f.key, screen: f.screen, title: f.title, acceptance: f.acceptance })))}\nNever file one of these again as a new finding — its verdict is its entry.\n` : '') +
      `Then list what is still or newly wrong: severity broken | needs-work | polish, a title, detail (with the region in image px), the files a fix edits (verified to exist), an acceptance line a later reviewer can judge from a screenshot, the viewports/themes/shots (\`<id>@<viewport>.<theme>\`) it shows on, systemic=true when a shared primitive or token is the cause. Ignore invisible lint noise; mocked data and seed names are fine. A screen whose shot is missing or blank goes to unreviewed.\n` +
      `Return batch ${b.id}, area ${b.area}, basis ${prep.reviewBasis} and screensRead (each screen id whose every PNG you read). Before returning, write your exact return JSON to ${passDir}/review/raw/${b.id}.json (it is the batch's checkpoint).`
    )), { label: `review:${b.id}`, phase: 'Review', schema: UILOOP_REVIEW_SCHEMA })
    const fresh = []
    for (let i = 0; i < now.length; i += 4) {
      fresh.push(...(await run.parallel(now.slice(i, i + 4).map(reviewer))).filter(Boolean))
    }
    const covered = new Set([...doneIds, ...fresh.map(r => r.batch)])
    const left = all.filter(b => !covered.has(b.id))
    const inScope = left.filter(b => !list(A.areas).length || list(A.areas).includes(b.area))
    // A batch is done once its reviewer ran; a screen it could not judge
    // (missing or blank shot) is never silently counted as reviewed — it is
    // named here and in the synthesis prompt, with the recapture that fixes it.
    if (fresh.some(r => r.basis !== prep.reviewBasis)) throw new Error('review-loop (ui-loop): reviewer returned a stale content fingerprint')
    const raw = [...prep.raw, ...fresh]
    const unread = all.flatMap(b => b.screens.filter(id => !raw.some(r => r.batch === b.id && (r.screensRead || []).includes(id))))
    const unreviewed = [...new Set([...raw.flatMap(r => r.unreviewed || []), ...unread])].sort()
    out.review = { batches: all.length, reviewedNow: fresh.length, left: left.map(b => b.id), unreviewed }
    if (unreviewed.length) out.problems.push(`${unreviewed.length} screens could not be reviewed (missing or blank shots): recapture with review-loop {mode: "ui-loop", stage: "capture", only: ${JSON.stringify(unreviewed)}} — ${unreviewed.join(', ')}`)
    // An `areas` limit narrows this run only: once its areas are done, the
    // chain drops it so the next run reviews the rest instead of looping.
    if (inScope.length) return Object.assign(out, { next: nextOf('review'), reason: `${inScope.length} review batches left` })
    if (left.length) return Object.assign(out, { next: { stage: 'review', args: Object.assign({}, carry, { stage: 'review', areas: undefined }) }, reason: `${left.length} review batches left outside areas ${list(A.areas).join(', ')}` })

    phase('Synthesize')
    const merged = mergeBacklog(prep.pass, prep.previousBacklog || [], [...(prep.raw || []), ...fresh])
    const synth = await run.agent(withPreamble(withUiLoop(
      `Write the deduplicated backlog of ui-loop pass ${prep.pass} to ${passDir}/review/backlog.json, in the \`vybava ui-loop scoreboard\` contract (docs/uiloop.md "Scoreboard and the review backlog": {v: 1, pass, findings}, unknown keys rejected).\n` +
      `Plain code already merged the reviewers' output (exact duplicates folded, previous items carry their verdict as status):\n${JSON.stringify(merged.backlog)}\n` +
      (merged.unjudged.length ? `No reviewer judged these previous items; they stand as not-met — look at their screens' shots and set the verdict when you can: ${JSON.stringify(merged.unjudged)}\n` : '') +
      (unreviewed.length ? `These screens had no usable shot, so nobody judged them — never mark an item on them met: ${JSON.stringify(unreviewed)}\n` : '') +
      (merged.problems.length ? `These findings lack a title, acceptance or files; repair them from the code and the shots, or drop one with why in problems: ${JSON.stringify(merged.problems)}\n` : '') +
      `Fold items that describe the same defect on the same screen into one (a carried item's key wins). Items sharing a root cause across screens stay one per screen and name the same files — the fix round groups them by file. Every file must exist; every item that is not met names the files a fix lane edits. No invented findings.\n` +
      `Also write {"basis":"${prep.reviewBasis}"} to ${passDir}/review/basis.json alongside the backlog (the backlog schema stays unchanged). Validate with \`vybava ui-loop scoreboard --pass ${prep.pass} --json\` (a BACKLOG_INVALID diagnostic names what to fix) and commit the backlog and its basis sidecar path-limited. Return the file, the finding and open counts and how many items you folded.`
    )), { label: 'synthesize', phase: 'Synthesize', schema: UILOOP_SYNTH_SCHEMA })
    if (!synth) throw new Error('review-loop (ui-loop): synthesis failed — run stage review again; the raw batches are kept')
    out.backlog = { file: synth.backlogFile, findings: synth.findings, open: synth.open }
    out.problems.push(...(synth.problems || []))

    phase('Scoreboard')
    const score = await run.agent(withPreamble(withUiLoop(
      `Score ui-loop pass ${prep.pass}: \`vybava ui-loop scoreboard --pass ${prep.pass} --json\`, then read ${passDir}/scoreboard.md.\n` +
      `On each area board ${JSON.stringify(out.boards)} post a callout in its "Pass ${prep.pass}" section: that area's row (screens broken / needs-work / polish / clean, findings open / met / partly / not-met, lint defects per rule, console errors, shots not ok, and the delta against the previous pass) and the totals line. Read \`docs {topic: "kind:board"}\` first; the callout replaces an earlier scoreboard callout of the same section. Return the scoreboard file, the totals and every board url you posted to.`
    )), { label: 'scoreboard', phase: 'Scoreboard', effort: 'low', schema: UILOOP_SCORE_SCHEMA })
    if (score) out.scoreboard = { file: score.scoreboardFile, totals: score.totals || {}, posted: score.posted }
    else out.problems.push('scoreboard: posting failed — `vybava ui-loop scoreboard` can be rerun by hand')
    const gate = !synth.open && !unreviewed.length && score ? await verifyGate() : null
    if (!synth.open && !unreviewed.length && !gatePassed(gate)) out.problems.push('the UI pass has no passing verification gate')
    return Object.assign(out, { next: nextOf(unreviewed.length ? 'capture' : synth.open ? 'fix' : null), receipt: completionReceipt({ complete: !synth.open && !unreviewed.length && gatePassed(gate), problems: out.problems, evidence: gatePassed(gate) ? [{ backlog: synth.backlogFile, shots: prep.shots, headSha: gate.headSha, ran: gate.ran }] : [] }) })
  }

  // ---- fix: primitives lanes first, then the primitive API is frozen and ≤ 4 area lanes run
  if (stage === 'fix') {
    const passDir = prep.passDir || `${cfg.out}/pass-${prep.pass}`
    const plan = planLanes(state.backlog, list(A.primitives), 4)
    const prim = remainingLanes(plan.primitives, state.checkpoints)
    const areas = remainingLanes(plan.areas, state.checkpoints)
    run.ensureBudget(prim.length + areas.length)
    log(`fix: ${plan.primitives.length} primitives lanes (${prim.length} unfinished), ${plan.areas.length} area lanes (${areas.length} unfinished), ${plan.frozen.length} primitive files`)
    const laneBrief = (l, kind, apiNotes) => withPreamble(withUiLoop(
      `Fix lane ${l.lane} of ui-loop pass ${prep.pass}, on branch ${prep.branch}. The spec is \`${cfg.spec}\`; the apps run on the devbox${prep.workspace ? ` workspace ${prep.workspace}` : ''} and stay running.\n` +
      `Items, in order (worst first) — each with the checkpoint file you write when it is finished (basis ${prep.reviewBasis}):\n${JSON.stringify(l.items.map(f => Object.assign({}, f, { checkpoint: checkpointPath(passDir, f.key) })))}\n` +
      (kind === 'primitives'
        ? `You own these primitives: the fix lands in the shared component or token, so every screen that uses it is fixed at once. Public API changes are ADDITIVE only — nothing removed or renamed — and each is documented in the spec's primitives section and returned in apiChanges. When you finish, the primitive API is frozen for the area lanes.\n`
        : `The primitive API is FROZEN: never edit these files — ${JSON.stringify(plan.frozen)}.${apiNotes.length ? ` Additions the primitives lanes made this round: ${JSON.stringify(apiNotes)}.` : ''} An item that needs a primitive change is checkpointed blocked with the exact change as its note (and returned in blocked).\n`) +
      `You are the ONLY writer and committer in this checkout while this lane runs. Other lanes run sequentially; never revert another lane's changes. Checkpoint JSON: {"v":1,"basis":"${prep.reviewBasis}","key","lane":"${l.lane}","status":"done|skipped|blocked","commit","screens":[the screen ids the fix changes],"note"} — commit it with the item. An item that already has a VALID checkpoint with basis ${prep.reviewBasis} is finished: skip it. Old or invalid checkpoints must be reevaluated.\n` +
      `Look at your fixes in a browser (onyx browser, headless) at the viewports and themes each item names — batch it: fix several items of one screen, look once; screenshots under ${passDir}/fix/shots/${l.lane}/. Never run \`vybava ui-loop run\` — the verify stage captures the whole round in one batch.\n` +
      `A skip needs a concrete reason (a design decision the spec does not settle is one). Return done/skipped/blocked keys, commits, touched screens, treeCleanOfMine.`
    , true))
    const runLanes = async (lanes, kind, apiNotes) => (await run.serial(lanes.map(l => () =>
      run.agent(laneBrief(l, kind, apiNotes), { label: `fix:${l.lane}`, phase: kind === 'primitives' ? 'Fix: primitives' : 'Fix: areas', schema: UILOOP_LANE_SCHEMA })))).filter(Boolean)
    const finishedBy = results => new Set(results.flatMap(r => [...r.done, ...r.skipped.map(s => s.key), ...(r.blocked || []).map(b => b.key)]))
    const results = []
    if (prim.length) {
      phase('Fix: primitives')
      results.push(...await runLanes(prim, 'primitives', []))
      const fin = finishedBy(results)
      const unfinished = prim.flatMap(l => l.items).filter(f => !fin.has(f.key))
      if (unfinished.length) {
        out.fix = laneSummary(results)
        return Object.assign(out, { next: nextOf('fix'), reason: `${unfinished.length} primitive items unfinished — the area lanes wait for a frozen primitive API` })
      }
    }
    if (areas.length) {
      phase('Fix: areas')
      results.push(...await runLanes(areas, 'areas', results.flatMap(r => r.apiChanges || [])))
    }
    out.fix = laneSummary(results)
    const fin = finishedBy(results)
    const left = [...prim, ...areas].flatMap(l => l.items).filter(f => !fin.has(f.key))
    const fixedAny = out.fix.done.length || state.checkpoints.some(c => c.status === 'done')
    out.handTest = 'The apps stay running on the devbox: ask the owner for a hand-test of the touched screens before the verify pass.'
    if (left.length) return Object.assign(out, { next: nextOf('fix'), reason: `${left.length} items without a checkpoint` })
    return Object.assign(out, { next: nextOf(fixedAny && prep.pass < cap ? 'verify' : null), reason: fixedAny ? (prep.pass < cap ? 'round checkpointed' : `cap of ${cap} passes reached`) : 'the round fixed nothing — the open items need a human' })
  }

  throw new Error(`review-loop (ui-loop): unknown stage ${stage} — capture | review | fix | verify | auto`)
}

function laneSummary(results) {
  return {
    lanes: results.map(r => r.lane),
    done: results.flatMap(r => r.done),
    skipped: results.flatMap(r => r.skipped),
    blocked: results.flatMap(r => r.blocked || []),
    commits: results.flatMap(r => r.commits || []),
    touchedScreens: [...new Set(results.flatMap(r => r.touchedScreens || []))],
    dirty: results.filter(r => !r.treeCleanOfMine).map(r => r.lane),
  }
}
// args: { mode?: 'routes' | 'ui-loop' — default ui-loop when no routes are passed and vybava.config.ts has a uiLoop section,
//   routes mode: routes?, journeys?, projectType?, matrix?, cap?: 3, severity?: 'minor'|'major'|'blocker',
//         task?, project?, board?, base?, scope?: string (what to test, prose)
//   ui-loop mode (lib/uiloop-review.js): stage?: 'auto'|'capture'|'review'|'fix'|'verify', pass?, cap?: 6 passes, fresh?,
//         apps?, only?, viewports?, themes?, workers?, wrap?, areas?, batch?: 14, reviewers?: 4, primitives?: path prefixes }
const A = args || {}
const run = workflowRun(A)
let mode = A.mode || (A.routes ? 'routes' : '')
if (!mode) {
  phase('Detect')
  const detected = await run.agent(withPreamble(UILOOP_DETECT_PROMPT), { label: 'detect', phase: 'Detect', effort: 'low', schema: UILOOP_DETECT_SCHEMA })
  mode = detected && detected.configured ? 'ui-loop' : 'routes'
  log(`review-loop: ${mode} mode${detected && detected.reason ? ` (${detected.reason})` : ''}`)
}
if (mode === 'ui-loop') {
  const result = await uiLoopReview(A, run)
  return run.finish(Object.assign({ receipt: completionReceipt() }, result))
}
if (mode !== 'routes') throw new Error(`review-loop: unknown mode ${mode} — routes | ui-loop`)
const cap = Math.max(1, Math.min(6, A.cap || 3))
const threshold = A.severity || 'minor'

phase('Prepare')
const prep = await run.agent(withPreamble(
  `Prepare this checkout for a review loop.\n` +
  `1. Report the current branch, headSha from git rev-parse HEAD, and the vitrinka project the repo is bound to (\`vitrinka status\` / the repo's .vitrinka descriptor).\n` +
  `2. Read \`.claude/vitrinka-workflows.json\` if it exists and return it as \`override\` ({} when absent).\n` +
  `3. Decide projectType (web | expo | cli | other) from the repo.\n` +
  `4. Start the app for this branch the way CLAUDE.md prescribes (devbox when available, else locally); wait until it answers; return the reachable base URL${A.base ? ` (requested: ${A.base})` : ''}.\n` +
  `5. Task binding: ${A.task ? `the run is bound to task ${A.task}.` : 'if the checkout carries a vt-<id> task, return it; otherwise leave task empty (the QA record lands on the project\'s Unplanned runs epic).'}\n` +
  `Never create tasks, boards or commits here.`
), { label: 'prepare', phase: 'Prepare', schema: PREPARE_SCHEMA })
if (!prep) throw new Error('review-loop: prepare failed')
if (A.expectedHead && prep.headSha !== A.expectedHead) throw new Error('review-loop: input revision changed; start a fresh verification instead of reusing old evidence')
if (A.continuation && !A.expectedHead) throw new Error('review-loop: a continuation requires expectedHead to bind its evidence')
const task = A.task || prep.task || ''
const project = A.project || prep.project || ''
const override = prep.override || {}
const { type, matrix, checklist, exclude } = resolveMatrix(A.projectType || prep.projectType, Object.assign({}, override, A.matrix ? { matrix: A.matrix } : {}))
if (!matrix.length) throw new Error(`review-loop: project type ${type} has no device matrix — nothing to shoot`)
const boardSlug = A.board || override.board || `${prep.branch.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}-review-loop`
log(`review-loop: ${type} on ${prep.branch} at ${prep.baseUrl} (${prep.where}), ${matrix.length} devices, cap ${cap}, threshold ${threshold}`)

phase('Map')
let terrain = A.routes ? { routes: A.routes, journeys: A.journeys || [] } : null
if (!terrain) {
  terrain = await run.agent(withPreamble(
    'Read-only: inventory every route/screen a user can reach in this repo (path, title, implementing file, auth, how to reach it with data on screen) and the 3-8 journeys a real user walks. Prefer the repo\'s own route tables and navigators over file-name guesses.'
  ), { label: 'inventory', phase: 'Map', agentType: 'Explore', schema: TERRAIN_SCHEMA })
}
if (!terrain || !terrain.routes || !terrain.routes.length) throw new Error('review-loop: no routes to shoot')
const allRoutes = terrain.routes.filter(r => !exclude.some(x => r.path === x || r.path.startsWith(x.replace(/\*$/, ''))))
if (!allRoutes.length) throw new Error('review-loop: all routes excluded; zero coverage cannot converge')
const allJourneys = terrain.journeys || []
if (!allJourneys.length) throw new Error('review-loop: no journeys to verify; supply a route inventory with user journeys')
log(`review-loop: ${allRoutes.length} routes, ${allJourneys.length} journeys`)

const captureRoot = (pass, device) => `.vitrinka/screenshots/review-loop/pass-${pass}/${device}`
const devLine = d => d.width ? `${d.name} ${d.width}×${d.height}@${d.scale} ${d.input}${d.safeArea ? ' with safe-area insets emulated' : ''}` : `${d.name} (${d.platform} simulator ${d.sim})`
// A viewport device is shot in the browser and adopted with --file; a simulator
// device (expo matrix: platform, no width) is captured natively by the CLI.
const captureStep = (d, pass) => {
  const tail = `--label pass${pass}/${d.name}/<route-slug> --title "<title>" --note "<what is on screen>" --src <implementing file> --root ${captureRoot(pass, d.name)} --yes`
  return d.width
    ? `open it at exactly this viewport, wait for it to settle, scroll the whole page once so lazy content is present, then capture 2× and adopt it with \`vitrinka board capture web --file <png> --route <path> --device ${d.name} --viewport ${d.width}x${d.height}@${d.scale || 2} ${tail}\``
    : `open it in the ${d.sim} simulator through its deep link and capture it with \`vitrinka board capture ${d.platform} --open <deep link> --route <path> --device ${d.name} ${tail}\``
}
// The usertest runs on the matrix's first device when the matrix is all simulators.
const native = matrix.every(d => !d.width)
const utPlatform = native ? matrix[0].platform : 'web'
const utDevice = native ? matrix[0].name : 'desktop'
const utWhere = `on EVERY matrix device: ${matrix.map(devLine).join(', ')}`

const resumed = A.continuation || {}
let headSha = prep.headSha
let routes = resumed.routes || allRoutes
let journeys = resumed.journeys || allJourneys
let regressList = resumed.regressList || []
const passes = resumed.passes || []
let boardUrl = resumed.boardUrl || ''
// Accepted and not fixed, ACROSS passes (openAfterPass): a skipped finding
// stays open and rides every later pass's fix list (fixListFor) until one
// fixes it, and the loop converges only on none.
let stillOpen = resumed.stillOpen || []
// Fixed in the pass the cap ended: gated, but no reshoot confirmed them.
let unverified = []
// Fixed usertest failures no later walk of their journey has confirmed yet
// (unwalkedFixes): each next pass walks them (journeysToRerun), and one still
// waiting when the loop ends is unverified.
let unwalked = resumed.unwalked || []
// A red gate is a fact of the loop, not of one pass: the last pass has no
// reshoot to show it, so the caller hears it here.
let gateRed = !!resumed.gateRed
let converged = false
const problems = [...(prep.problems || [])]
// A 'rewalk' pass end (passEnd): the next pass only walks the unwalked fixes
// again — nothing changed since the last shots, so it shoots and reviews nothing.
let walkOnly = !!resumed.walkOnly

let next = null
const firstPass = resumed.pass || 1
run.ensureBudget((walkOnly ? 0 : matrix.length + 2) + 2) // capture + publish + review + usertest + gate/fix
for (let pass = firstPass; pass <= Math.min(cap, firstPass); pass++) {
  const ph = `Pass ${pass}`
  phase('Capture')
  const isFirst = pass === 1
  log(walkOnly ? `${ph}: walking ${unwalked.length} fixed journeys again, nothing to shoot` : `${ph}: shooting ${routes.length} routes on ${matrix.length} devices, ${journeys.length} journeys`)

  const shooters = walkOnly ? [] : matrix.map(d => () => run.agent(withPreamble(
    `Shoot pass ${pass} of a review loop on device ${devLine(d)} against ${prep.baseUrl}.\n` +
    `Routes (shoot every one, with data on screen; a route needing setup says how):\n${JSON.stringify(routes)}\n` +
    `Read \`docs {topic: "guide:publish-capture"}\` first. For each route: ${captureStep(d, pass)}. On a touch device also capture one screen with a menu/sheet open when the route has one. Read each saved image back and re-shoot a blank or half-loaded one. Return every shot; a route you could not reach is a \`problems\` line naming why.`
  ), { label: `shoot:${d.name}`, phase: 'Capture', schema: SHOOT_SCHEMA }))

  const tester = () => run.agent(withPreamble(
    `Exploratory usertest, pass ${pass}, against ${prep.baseUrl} ${utWhere}.\n` +
    `Journeys to walk:\n${JSON.stringify(journeys)}\n${A.scope ? `Focus: ${A.scope}\n` : ''}` +
    (unwalked.length ? `Fixed failures to walk again — each is ONE case on its device under exactly this title (a journey above with the same title is that case), so the loop can tell the fix held:\n${JSON.stringify(rewalkCases(unwalked))}\n` : '') +
    `Follow the vitrinka usertest skill's lane 2 (\`vitrinka qa usertest start${task ? ` --task ${task}` : ''} --app ${type} --platform ${utPlatform} --device ${utDevice} --yes\`, then \`case\`, captures, \`verdict\`, and \`finish --bugs direct --yes\`). One case per journey per device, titled with the journey's title verbatim (a failure is tracked across passes by that title); a fail carries --note with the exact contract broken and the implementing files. Understand before judging: read the code behind a suspicious behaviour. Never touch production tenants. Return the cases with verdicts and the bug task urls \`finish\` printed.`
  ), { label: 'usertest', phase: 'Capture', schema: USERTEST_SCHEMA })

  const results = (await run.parallel([...shooters, tester])).filter(Boolean)
  const shots = results.filter(r => r.shots)
  const ut = results.find(r => r.cases) || { cases: [], bugs: [] }
  const shotCount = shots.reduce((n, s) => n + s.shots.length, 0)
  if (!shotCount && !walkOnly) throw new Error(`${ph}: no screenshots captured — the app or the browser is not reachable`)
  unwalked = unwalkedFixes(unwalked, ut.cases)

  if (!walkOnly) phase('Boards')
  const pub = walkOnly ? null : await run.agent(withPreamble(
    `Compose pass ${pass} of a review loop onto ONE run board (slug ${boardSlug}${project ? `, project ${project}` : ''}${task ? `, task ${task}` : ''}).\n` +
    `Sets captured this pass (one capture root per device): ${JSON.stringify(shots.map(s => ({ device: s.device, root: captureRoot(pass, s.device), shots: s.shots })))}.\n` +
    `Usertest record: ${JSON.stringify({ qaTaskUrl: ut.qaTaskUrl, boardUrl: ut.boardUrl, cases: ut.cases })}.\n` +
    `Structure: section "Pass ${pass}" with one row per device in matrix order, shots ordered by route; a summary card at the section head naming the pass, the device matrix, the shot count and the usertest verdict tally, with a portal link to the usertest board when it is a different board. Earlier pass sections stay untouched. Return the board's server url, its slug, the section title and every shot card id with its route and device.`
  ), { label: 'publish', phase: 'Boards', agentType: 'vitrinka:vitrinka-publisher', schema: PUBLISH_SCHEMA })
  if (!pub && !walkOnly) throw new Error(`${ph}: publishing failed`)
  if (pub) boardUrl = pub.boardUrl

  if (!walkOnly) phase('Review')
  const reviewers = walkOnly ? [] : [() => run.agent(withPreamble(
    `Local review (you are the reviewer, no server-side judge) of pass ${pass}, all devices ${matrix.map(d => d.name).join(', ')}, on board ${pub.boardSlug} (${pub.boardUrl}).\n` +
    `Cards in scope: ${JSON.stringify(pub.cards)}.\n` +
    `Read \`review_brief${project ? ` {project: "${project}"}` : ''}\` and judge against it PLUS this checklist:\n- ${checklist.join('\n- ')}\n` +
    `Read every card's pixels with get_card_image before filing anything (cross-cutting problems show only across the set). File ONE \`annotate {board, agent: "claude-code", items: [...]}\` batch: each item keyed \`p${pass}-<device>-<n>\`, region measured on the source pixels, category = the rule id, severity blocker|major|minor, and detail naming the implementing files and what correct looks like. Sort defects as kind "finding" and taste as "suggestion".\n` +
    (regressList.length ? `Regression check — these findings were fixed last pass; for each, look at the same route on this device and report fixed true/false with a note:\n${JSON.stringify(regressList.map(f => ({ key: f.key, id: f.id, route: f.route, summary: f.summary })))}\n` : '') +
    (stillOpen.length ? `Already filed and still open (accepted earlier, not fixed) — never file these again, under any key; file only defects not on this list:\n${JSON.stringify(stillOpen.map(f => ({ key: f.key, id: f.id, route: f.route, device: f.device, summary: f.summary })))}\n` : '') +
    `Return cardsRead with EVERY cardId whose image you read; screensRead is their count. Return every finding with its annotation id from the receipt, its route, device, an \`area\` (the component or route the fix lives in) and the files it names.`
  ), { label: 'review:devices', phase: 'Review', schema: FINDINGS_SCHEMA })]
  const reviews = (await run.parallel(reviewers)).filter(Boolean)
  problems.push(...coverageProblems(routes, matrix, shots, journeys, ut.cases, reviews, walkOnly, pub ? pub.cards : []))
  problems.push(...shots.flatMap(s => s.problems || []))
  const seen = new Set()
  const filed = reviews.flatMap(r => r.findings).filter(f => { const k = key(f); if (seen.has(k)) return false; seen.add(k); return true })
  const regressions = reviews.flatMap(r => r.regressions || [])
  const regressed = regressList.filter(f => regressions.some(r => r.key === f.key && r.fixed === false))
  const missingRegressions = regressList.filter(f => f.rule !== 'functional' && !regressions.some(r => r.key === f.key))
  problems.push(...missingRegressions.map(f => `fixed finding not reviewed again: ${f.key}`))
  const functional = functionalFindings(ut.cases)
  const accepted = autoAcceptable(filed, threshold)
  const fixList = fixListFor([...accepted, ...functional, ...regressed], stillOpen)
  const parked = filed.length - accepted.length
  passes.push({ pass, shots: shotCount, filed: filed.length, functionalFails: functional.length, regressed: regressed.length, toFix: fixList.length, parked })
  log(`${ph}: ${shotCount} shots, ${filed.length} findings filed (${parked} left staged for the human), ${functional.length} functional fails, ${regressed.length} regressions, ${stillOpen.length} carried open`)

  const end = passEnd(pass, cap, fixList.length, unwalked.length)
  // A fixed journey no walk confirmed (its tester died or skipped it), or a
  // gate an earlier pass left red, is no convergence, even on a pass with
  // nothing left to fix.
  if (end === 'clean') {
    phase('Gate')
    const gate = await run.agent(withPreamble(
      `Verify this clean UI pass WITHOUT editing or committing: run the repo's type/build/test gates where CLAUDE.md prescribes. Report testsExecuted from the runner counts; an expected suite with zero executed tests fails. Return green, ran, failures and headSha from git rev-parse HEAD. The screenshots were captured at ${headSha}; a different HEAD fails this gate.`
    ), { label: 'gate:clean', phase: 'Gate', schema: GATE_SCHEMA })
    gateRed = !gatePassed(gate) || gate.headSha !== headSha
    converged = !problems.length && convergedAfter({ clean: true, open: stillOpen, unwalked, gateRed })
    log(`${ph}: clean — ${converged ? 'loop converged' : [unwalked.length ? `${unwalked.length} fixed journeys never walked again` : '', gateRed ? 'a pass gate stayed red' : ''].filter(Boolean).join('; ') + ', so it did not converge'}`)
    break
  }
  if (end === 'rewalk') {
    walkOnly = !problems.length
    if (walkOnly) regressList = [] // pixels were judged; only the functional rewalk remains
    else routes = allRoutes // recover missing visual coverage before claiming convergence
    journeys = journeysToRerun(allJourneys, [], unwalked, ut.cases)
    log(`${ph}: nothing to fix, ${unwalked.length} fixed journeys never walked again — the next pass only walks them`)
    next = { stage: 'verify', args: Object.assign({}, A, { agentBudget: undefined, expectedHead: headSha, routes: allRoutes, journeys: allJourneys, continuation: { pass: pass + 1, routes, journeys, regressList, passes, boardUrl, stillOpen, unwalked, gateRed, walkOnly } }) }
    continue
  }

  const ids = uniq(accepted.map(f => f.id))
  phase('Fix')
  const fixer = await run.agent(withPreamble(
    `You are the ONLY writer and committer in this checkout. Fix ALL findings below sequentially, shared components before their consumers; never revert other work.\n` +
    `First accept only these newly staged annotation ids through the documented agent-verdict door: ${JSON.stringify(ids)} on board ${pub ? pub.boardSlug : boardSlug}. Do not re-accept carried ids.\n` +
    `Findings: ${JSON.stringify(fixList)}. Commit path-limited per coherent unit, reply with the commit, and set in_review. A design decision is skipped with why.\n` +
    `Then in THIS SAME agent run the repo's type/build/test gates where CLAUDE.md prescribes. Repair and commit introduced failures; report prior ones. Report testsExecuted from the runner counts; zero executed tests cannot pass an expected suite. Return fixed/skipped keys, touchedRoutes, touchedFiles, commits, and gate {green, ran, testsExecuted, failures, repaired, headSha} after all verification. Leave the app running.`
  ), { label: 'fix:batch', phase: 'Fix', schema: { type: 'object', properties: Object.assign({}, FIX_SCHEMA.properties, { gate: GATE_SCHEMA }), required: [...FIX_SCHEMA.required, 'gate'] } })
  if (!fixer) throw new Error(`${ph}: fixer failed; resume this run before advancing`)
  const fixedKeys = new Set(fixer.fixed)
  const touchedRoutes = uniq(fixer.touchedRoutes)
  const touchedFiles = uniq(fixer.touchedFiles)
  const gate = fixer.gate
  headSha = gate && gate.headSha || headSha
  gateRed = !gatePassed(gate)
  if (gateRed) log(`${ph}: verification gate has no passing evidence`)

  regressList = fixList.filter(f => fixedKeys.has(f.key))
  unwalked = [...unwalked.filter(f => !fixedKeys.has(f.key)), ...regressList.filter(f => f.rule === 'functional')]
  stillOpen = openAfterPass(stillOpen, fixList, fixedKeys)
  if (end === 'last') {
    unverified = regressList
    log(`${ph}: cap reached — ${unverified.length} fixed with no reshoot to verify them, ${stillOpen.length} open on the board (raise cap to continue)`)
    break
  }
  walkOnly = false
  const openRoutes = uniq([...touchedRoutes, ...fixList.filter(f => !fixedKeys.has(f.key)).map(f => f.route)])
  routes = allRoutes.filter(r => openRoutes.some(p => p && (r.path === p || r.path.startsWith(p))))
  if (!routes.length) routes = allRoutes.filter(r => touchedFiles.some(f => r.file && f === r.file))
  const sharedChange = !!(gate && gate.repaired) || touchedFiles.some(f => !allRoutes.some(r => r.file === f)) || !touchedFiles.length
  if (problems.length || sharedChange) routes = allRoutes // partial coverage must be recovered before narrowing
  if (!routes.length) routes = allRoutes
  journeys = sharedChange ? allJourneys : journeysToRerun(allJourneys, openRoutes, unwalked, ut.cases)
  next = { stage: 'verify', args: Object.assign({}, A, { agentBudget: undefined, expectedHead: headSha, routes: allRoutes, journeys: allJourneys, continuation: { pass: pass + 1, routes, journeys, regressList, passes, boardUrl, stillOpen, unwalked, gateRed, walkOnly } }) }
  log(`${ph}: next pass reshoots ${routes.length} routes, reruns ${journeys.length} journeys`)
}
// A fixed journey no later walk confirmed is as unverified as a last-pass fix.
unverified = [...unverified, ...unwalked.filter(f => !unverified.some(u => u.key === f.key))]

return run.finish({
  next,
  headSha,
  problems,
  receipt: completionReceipt({ complete: converged, open: stillOpen, unverified, problems: [...problems, ...(gateRed ? ['verification gate red'] : [])], evidence: boardUrl && passes.length ? [{ boardUrl, headSha, passes: passes.length }] : [] }),
  boardUrl,
  branch: prep.branch,
  task,
  passes,
  converged,
  gateRed,
  open: stillOpen.map(f => ({ key: f.key, id: f.id, summary: f.summary })),
  unverified: unverified.map(f => ({ key: f.key, id: f.id, summary: f.summary })),
})
